-- Drop old objects so the script can be re-run safely
BEGIN
  FOR t IN (SELECT table_name FROM user_tables
             WHERE table_name IN ('ORDER_STATUS_AUDIT','INVENTORY_LOG','ORDER_ITEMS',
                                  'ORDERS','CART_ITEMS','BOOKS','CATEGORIES','USERS')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

-- ---------------------------------------------------------------------
-- Master tables
-- ---------------------------------------------------------------------
CREATE TABLE categories (
  category_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR2(60)  NOT NULL,
  description   VARCHAR2(300),
  icon          VARCHAR2(40),
  CONSTRAINT uq_category_name UNIQUE (name)
);

CREATE TABLE users (
  user_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name     VARCHAR2(100) NOT NULL,
  email         VARCHAR2(120) NOT NULL,
  password_hash VARCHAR2(64)  NOT NULL,
  phone         VARCHAR2(20),
  address       VARCHAR2(300),
  role          VARCHAR2(10)  DEFAULT 'CUSTOMER' NOT NULL,
  created_at    DATE          DEFAULT SYSDATE,
  CONSTRAINT uq_user_email UNIQUE (email),
  CONSTRAINT chk_user_role CHECK (role IN ('CUSTOMER','ADMIN'))
);

CREATE TABLE books (
  book_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title         VARCHAR2(200) NOT NULL,
  author        VARCHAR2(120) NOT NULL,
  isbn          VARCHAR2(20),
  category_id   NUMBER        NOT NULL,
  price         NUMBER(8,2)   NOT NULL,
  stock         NUMBER(6)     DEFAULT 0 NOT NULL,
  description   VARCHAR2(2000),
  cover_image   VARCHAR2(100),
  publisher     VARCHAR2(100),
  pub_year      NUMBER(4),
  pages         NUMBER(5),
  rating        NUMBER(2,1)   DEFAULT 4.0,
  is_active     CHAR(1)       DEFAULT 'Y' NOT NULL,
  created_at    DATE          DEFAULT SYSDATE,
  CONSTRAINT fk_book_category FOREIGN KEY (category_id) REFERENCES categories(category_id),
  CONSTRAINT uq_book_isbn   UNIQUE (isbn),
  CONSTRAINT chk_book_price CHECK (price > 0),
  CONSTRAINT chk_book_stock CHECK (stock >= 0),
  CONSTRAINT chk_book_rate  CHECK (rating BETWEEN 0 AND 5),
  CONSTRAINT chk_book_active CHECK (is_active IN ('Y','N'))
);

-- ---------------------------------------------------------------------
-- Transaction tables
-- ---------------------------------------------------------------------
CREATE TABLE cart_items (
  cart_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       NUMBER NOT NULL,
  book_id       NUMBER NOT NULL,
  quantity      NUMBER(3) DEFAULT 1 NOT NULL,
  added_at      DATE DEFAULT SYSDATE,
  CONSTRAINT fk_cart_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
  CONSTRAINT fk_cart_book FOREIGN KEY (book_id) REFERENCES books(book_id) ON DELETE CASCADE,
  CONSTRAINT uq_cart_user_book UNIQUE (user_id, book_id),
  CONSTRAINT chk_cart_qty CHECK (quantity BETWEEN 1 AND 99)
);

CREATE TABLE orders (
  order_id         NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
  user_id          NUMBER NOT NULL,
  order_date       DATE DEFAULT SYSDATE,
  subtotal         NUMBER(10,2) NOT NULL,
  shipping_charge  NUMBER(8,2)  DEFAULT 0,
  total_amount     NUMBER(10,2) NOT NULL,
  status           VARCHAR2(15) DEFAULT 'PLACED' NOT NULL,
  shipping_address VARCHAR2(300) NOT NULL,
  payment_method   VARCHAR2(20) NOT NULL,
  payment_ref      VARCHAR2(40),
  CONSTRAINT fk_order_user FOREIGN KEY (user_id) REFERENCES users(user_id),
  CONSTRAINT chk_order_status CHECK (status IN ('PLACED','SHIPPED','DELIVERED','CANCELLED')),
  CONSTRAINT chk_order_pay CHECK (payment_method IN ('CARD','UPI','COD'))
);

CREATE TABLE order_items (
  order_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      NUMBER NOT NULL,
  book_id       NUMBER NOT NULL,
  quantity      NUMBER(3) NOT NULL,
  unit_price    NUMBER(8,2) NOT NULL,
  CONSTRAINT fk_oi_order FOREIGN KEY (order_id) REFERENCES orders(order_id) ON DELETE CASCADE,
  CONSTRAINT fk_oi_book  FOREIGN KEY (book_id)  REFERENCES books(book_id)
);

-- ---------------------------------------------------------------------
-- Audit tables (filled automatically by triggers)
-- ---------------------------------------------------------------------
CREATE TABLE inventory_log (
  log_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id     NUMBER NOT NULL,
  old_stock   NUMBER(6),
  new_stock   NUMBER(6),
  change_qty  NUMBER(6),
  reason      VARCHAR2(30),
  changed_at  DATE DEFAULT SYSDATE
);

CREATE TABLE order_status_audit (
  audit_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    NUMBER NOT NULL,
  old_status  VARCHAR2(15),
  new_status  VARCHAR2(15),
  changed_by  VARCHAR2(60),
  changed_at  DATE DEFAULT SYSDATE
);

-- ---------------------------------------------------------------------
-- Indexes
-- ---------------------------------------------------------------------
CREATE INDEX idx_books_category ON books(category_id);
CREATE INDEX idx_books_title    ON books(UPPER(title));
CREATE INDEX idx_orders_user    ON orders(user_id);
CREATE INDEX idx_oi_order       ON order_items(order_id);
CREATE INDEX idx_invlog_book    ON inventory_log(book_id);

-- ---------------------------------------------------------------------
-- View used by every book query from the application
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW v_book_catalog AS
SELECT b.book_id, b.title, b.author, b.isbn, b.category_id, c.name AS category_name,
       b.price, b.stock, b.description, b.cover_image, b.publisher, b.pub_year,
       b.pages, b.rating, b.is_active, b.created_at
  FROM books b
  JOIN categories c ON c.category_id = b.category_id;
